/**
 * 构造一张冻结的题卡，嵌套的数组与对象一并冻结。
 *
 * @param {string} id 题卡 ID，形如 A01-01
 * @param {object} definition 题卡的其余字段
 * @returns {object} 冻结后的题卡
 */
function card(id, definition) {
  return Object.freeze({
    id,
    ...definition,
    prepGuide: Object.freeze({ ...definition.prepGuide, questions: Object.freeze(definition.prepGuide.questions), stepHints: Object.freeze(definition.prepGuide.stepHints) }),
    bestAnswer: Object.freeze(definition.bestAnswer.map((item) => Object.freeze(item))),
    badExample: Object.freeze({ ...definition.badExample, problems: Object.freeze(definition.badExample.problems) }),
    study: Object.freeze(definition.study),
  });
}

