/**
 * 构造一张冻结的题卡，嵌套的数组与对象一并冻结。
 *
 * @param {string} id 题卡 ID，形如 F01-01
 * @param {object} definition 题卡的其余字段
 * @returns {object} 冻结后的题卡
 */
