/**
 * 第四阶段“能推动”：第 22–27 课。
 *
 * 目标是让别人因为你的话而行动：争取资源、拒绝与划边界、批评反馈、
 * 协调冲突、谈判议价、用提问做调研。示范中的人名、数字与经历均为模拟情境。
 */

function step(label, purpose, phrase) {
  return Object.freeze({ label, purpose, phrase });
}

function line(stepIndex, text, why) {
  return Object.freeze({ step: stepIndex, text, why });
}

function framework(name, source, mapping) {
  return Object.freeze({ name, source, mapping });
}

/**
 * 构造一课冻结的范式数据，嵌套的数组与对象一并冻结。
 *
 * @param {string} id 课 ID，必须出现在 PARADIGM_IDS 中
 * @param {object} definition 课的其余字段（设计 §5.1）
 * @returns {object} 冻结后的课
 */
function paradigm(id, definition) {
  return Object.freeze({
    id,
    ...definition,
    frameworks: Object.freeze(definition.frameworks),
    steps: Object.freeze(definition.steps),
    model: Object.freeze(definition.model),
    example: Object.freeze(definition.example),
    weak: Object.freeze({ ...definition.weak, problems: Object.freeze(definition.weak.problems) }),
    transferContextIds: Object.freeze(definition.transferContextIds),
  });
}

