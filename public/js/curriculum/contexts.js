/**
 * 构造一类冻结的语境模板，数组字段一并冻结。
 *
 * @param {string} id 语境 ID，前缀 A/L/B/F 对应四条线
 * @param {object} definition 语境的其余字段（设计 §6.1）
 * @returns {object} 冻结后的语境
 */
function context(id, definition) {
  return Object.freeze({
    id,
    ...definition,
    paradigmIds: Object.freeze(definition.paradigmIds),
    keyChecks: Object.freeze(definition.keyChecks),
    interrupts: Object.freeze(definition.interrupts),
    followups: Object.freeze(definition.followups),
  });
}

